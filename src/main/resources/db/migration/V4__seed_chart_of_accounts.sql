-- Insert parents before children; the parent is the longest existing code that prefixes the child.
DO
$$
DECLARE
    seed   RECORD;
    parent accounts%ROWTYPE;
BEGIN
    FOR seed IN SELECT * FROM seed_accounts ORDER BY length(code), code LOOP
        SELECT * INTO parent FROM accounts
        WHERE seed.code LIKE code || '%' AND length(code) < length(seed.code)
        ORDER BY length(code) DESC
        LIMIT 1;

        INSERT INTO accounts (code, name, parent_id, level, element, nature, accepts_entries)
        VALUES (seed.code,
                seed.name,
                parent.id,
                COALESCE(parent.level + 1, 1),
                CASE substr(seed.code, 1, 1)
                    WHEN '1' THEN 'ASSET' WHEN '2' THEN 'LIABILITY' WHEN '3' THEN 'EQUITY'
                    WHEN '4' THEN 'INCOME' ELSE 'EXPENSE' END,
                CASE seed.nature WHEN 'D' THEN 'DEBIT' ELSE 'CREDIT' END,
                seed.accepts);
    END LOOP;
END;
$$;
